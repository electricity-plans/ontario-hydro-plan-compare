// Build dist/index.html: one self-contained file (engine + UI + styles), no network, no install.
// Usage: node tools/build.mjs
// The bundler is deliberately tiny: it understands only the import/export forms this repo uses,
// and fails loudly on anything else.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, normalize, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const rel = p => relative(ROOT, p).split('\\').join('/');

export function bundleEngine(entry = 'src/index.js') {
  const mods = new Map();
  const visit = file => {
    const key = rel(join(ROOT, file));
    if (mods.has(key)) return key;
    mods.set(key, null);
    let code = readFileSync(join(ROOT, key), 'utf8');
    const exportsList = [];
    const resolve = spec => { if (!spec.startsWith('.')) throw new Error(`${key}: only relative imports are supported (${spec})`); return visit(rel(normalize(join(ROOT, dirname(key), spec)))); };
    let n = 0;
    code = code.replace(/^export\s*\{([^}]*)\}\s*from\s*'([^']+)';?$/gm, (_, names, spec) => {
      const v = `__re${n++}`; const dep = resolve(spec);
      for (const part of names.split(',').map(s => s.trim()).filter(Boolean)) { const [a, b] = part.split(/\s+as\s+/); exportsList.push([b || a, `${v}.${a}`]); }
      return `const ${v} = __req(${JSON.stringify(dep)});`;
    });
    code = code.replace(/^import\s*\{([^}]*)\}\s*from\s*'([^']+)';?$/gm, (_, names, spec) =>
      `const { ${names.split(',').map(s => s.trim()).filter(Boolean).map(p => p.replace(/\s+as\s+/, ': ')).join(', ')} } = __req(${JSON.stringify(resolve(spec))});`);
    code = code.replace(/^export\s+(function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm, (_, kw, name) => { exportsList.push([name, name]); return `${kw} ${name}`; });
    if (/^\s*(import|export)\b/m.test(code)) throw new Error(`${key}: unsupported import/export form:\n` + code.match(/^\s*(import|export)\b.*$/m)[0]);
    mods.set(key, `__def(${JSON.stringify(key)}, function (__req) {\n${code}\nreturn { ${exportsList.map(([k, v]) => (k === v ? k : `${k}: ${v}`)).join(', ')} };\n});`);
    return key;
  };
  const entryKey = visit(entry);
  return `/* Engine bundle, generated by tools/build.mjs. Do not edit; edit src/ and tariffs/ instead. */
(function (global) {
'use strict';
var __mods = {}, __cache = {}, __loading = {};
function __def(name, fn) { __mods[name] = fn; }
function __req(name) { if (__cache[name] === __loading) throw new Error('Circular import: ' + name); if (!(name in __cache)) { __cache[name] = __loading; __cache[name] = __mods[name](__req); } return __cache[name]; }
${[...mods.values()].join('\n')}
global.Engine = __req(${JSON.stringify(entryKey)});
})(typeof self !== 'undefined' ? self : globalThis);
`;
}

export function buildHtml() {
  const engine = bundleEngine();
  const html = readFileSync(join(ROOT, 'app/index.html'), 'utf8')
    .replace('/*__STYLES__*/', () => readFileSync(join(ROOT, 'app/styles.css'), 'utf8'))
    .replace('/*__ENGINE__*/', () => engine)
    .replace('/*__WORKER__*/', () => readFileSync(join(ROOT, 'app/worker.js'), 'utf8'))
    .replace('/*__UI__*/', () => readFileSync(join(ROOT, 'app/ui.js'), 'utf8'))
    .replace('__BUILD__', process.env.BUILD_DATE || new Date().toISOString().slice(0, 10))   // BUILD_DATE makes the build reproducible (CI uses the committed date)
    .replace('__VERSION__', JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8')).version);
  if (/\/\*__[A-Z]+__\*\//.test(html)) throw new Error('Unreplaced placeholder in app/index.html');
  if (/<script[^>]+src=|<link[^>]+href=["']https?:/i.test(html)) throw new Error('dist must not load external resources');
  return html;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === normalize(process.argv[1])) {
  mkdirSync(join(ROOT, 'dist'), { recursive: true });
  const html = buildHtml();
  writeFileSync(join(ROOT, 'dist/index.html'), html);
  console.log(`dist/index.html written (${(html.length / 1024).toFixed(0)} KB)`);
}
